/**
 * Только цифры из строки: «123 456» → «123456», «12-34» → «1234». Для кода из сообщения и телефона в схемах входа
 * (zod `.transform(digitsOnly)`): поле принимает вставку с пробелами и дефисами, а нецифровые символы убирает схема.
 * Юникод-цифры других письменностей не считаются цифрами (только 0–9).
 */
export function digitsOnly(value: string): string {
  return value.replace(/[^0-9]/g, "");
}
