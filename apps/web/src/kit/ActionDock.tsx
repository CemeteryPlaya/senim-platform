import type { ReactNode } from "react";

/**
 * Док главного действия экрана: кнопка (и, если нужно, тихая рядом) там, где её достаёт большой палец.
 *
 * Механизм. Телефон: док — `sticky` в потоке содержимого; его `bottom` = высота панели вкладок + зазор 8 px + её
 * собственный отступ от низа (утилита `dock-above-bar`, tokens.css). Высоту панели даёт переменная `--tab-bar-height`:
 * `TabBar` измеряет себя (ResizeObserver) и пишет её в оболочку, так что при крупном шрифте и подписях в две строки док
 * остаётся над панелью, а не под ней. До измерения и без JavaScript действует запасное значение однострочной панели
 * (оболочка с вкладками помечена `data-has-tabs`). Там, где вкладок нет (оператор), переменной нет: док прилипает к низу
 * с тем же отступом 10 px плюс безопасная зона. В конце страницы `sticky` отпускает док, и он встаёт обычным блоком под
 * содержимым.
 *
 * Материал. Полупрозрачная панель `glass` с рамкой и тенью `float`, того же радиуса и с теми же боковыми отступами
 * 10 px, что у панели вкладок (утилита `dock-bleed` выводит её за поля содержимого). Стекло на стекле не кладётся: док
 * стоит выше панели вкладок с зазором и её не перекрывает; перекрывает он только содержимое страницы, где и нужны
 * плотность 85 % и размытие. Кнопка внутри сплошная (`bg-action`) — подпись читается на любом фоне; при
 * prefers-reduced-transparency панель сплошная (утилита `glass`).
 *
 * Компьютер: никакого прилипания — обычный блок в потоке, кнопки в ряд по своей ширине. Ширину детей задаёт сам док:
 * на телефоне каждый на всю ширину, на компьютере по своей — `full` у кнопок внутри не ставится. Внутрь кладётся ровно
 * одно главное действие экрана (`Button` / `ButtonLink` без `variant`), рядом — не более одной тихой.
 *
 * Дети дока — только кнопки и ссылки, напрямую: `<form>` внутри дока получит ширину вместо кнопки. Если док стоит
 * вне формы, связывайте кнопку с ней атрибутом `form="id-формы"`; если нужна форма целиком — кладите док внутрь неё.
 *
 * Док — ПОСЛЕДНИЙ ребёнок корневой колонки экрана: залипание `sticky` ограничено родителем, и док внутри `Card` или
 * посреди колонки залипает только в пределах этого блока. Серверный компонент.
 */
export function ActionDock({ children }: { children: ReactNode }) {
  return (
    <div data-action-dock className="flex flex-col gap-stack-tight mobile:sticky mobile:z-10 mobile:glass mobile:dock-above-bar mobile:dock-bleed mobile:rounded-bar mobile:border mobile:border-line mobile:p-2 mobile:shadow-float mobile:*:w-full desktop:flex-row desktop:flex-wrap desktop:items-center desktop:*:w-auto">
      {children}
    </div>
  );
}
