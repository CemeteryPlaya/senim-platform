/** «0:45» — минуты и секунды до повторной отправки кода. */
const clock = (seconds: number) => `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, "0")}`;

/** Месяцы в родительном падеже: «11 ноября 2026». */
const MONTHS = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"] as const;

/** «Редакция от 11 ноября 2026» из версии вида «2026-11-11-d1»; версия без даты в начале — как есть. */
function editionLabel(version: string): string {
  const match = /^(\d{4})-(\d{2})-(\d{2})(?!\d)/.exec(version);
  const month = match ? MONTHS[Number(match[2]) - 1] : undefined;
  if (!match || !month || Number(match[3]) < 1 || Number(match[3]) > 31) return `Редакция ${version}`;
  return `Редакция от ${Number(match[3])} ${month} ${match[1]}`;
}

