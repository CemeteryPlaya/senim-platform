import { describe, expect, it } from "vitest";
import { formatPhone, parsePhone } from "./phone";

describe("parsePhone", () => {
  it.each([
    ["+7 700 000 01 01", "+77000000101"],
    ["+77000000101", "+77000000101"],
    ["8 (700) 000-01-01", "+77000000101"],
    ["77000000101", "+77000000101"],
    ["7000000101", "+77000000101"],
    ["  +7-747-123-45-67 ", "+77471234567"],
  ])("приводит %s к %s", (raw, expected) => {
    expect(parsePhone(raw)).toBe(expected);
  });

  it.each([
    ["", "пусто"],
    ["+7 700 000 01", "мало цифр"],
    ["+7 700 000 01 011", "много цифр"],
    ["+7 912 345 67 89", "не казахстанский мобильный (не 7xx)"],
    ["+1 202 555 01 01", "чужая страна"],
    ["+7 700 abc 01 01", "буквы"],
  ])("отклоняет %s (%s)", (raw) => {
    expect(parsePhone(raw)).toBeNull();
  });
});

describe("formatPhone", () => {
  it("показывает номер группами", () => {
    expect(formatPhone("+77000000101")).toBe("+7 700 000 01 01");
  });
});
