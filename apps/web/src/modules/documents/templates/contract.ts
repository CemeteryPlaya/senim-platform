import { brand } from "@/config/brand";
import type { Block, PdfSpec } from "../pdf/spec";
import { LEGAL_REVIEW_NOTICE, TEMPLATE_EDITION, date, money, months } from "./common";
import type { ContractData, DealMoney, ExecutorParty } from "./types";

/*
 * Оферта (договор сделки) по ТЗ MVP v1.0 и ADR-009. ПРОЕКТ: текст требует юридической проверки
 * (пометка — в колонтитуле каждой страницы). Текст не обещает больше, чем делает продукт:
 * платформа не сторона договора и не принимает деньги; деньги покупателя лежат на эскроу-счёте банка.
 * В оферте слово «эскроу» допустимо (ADR-009, раздел 2.1.4 решений владельца).
 */

/** ТОО действует через директора; ИП и самозанятый — сами. ИИН/БИН раскрываются только здесь. */
export function executorParty({ legalForm, legalName, binIin, signerFullName }: ExecutorParty): string {
  switch (legalForm) {
    case "TOO":
      return signerFullName
        ? `${legalName}, БИН ${binIin}, в лице директора ${signerFullName}, действующего на основании Устава`
        : `${legalName}, БИН ${binIin}`;
    case "IP":
      return `${legalName} (индивидуальный предприниматель), ИИН ${binIin}`;
    case "SELF_EMPLOYED":
      return `${legalName} (самозанятый), ИИН ${binIin}`;
  }
}

export const clientParty = (c: { fullName: string; iin: string | null }) => (c.iin ? `${c.fullName}, ИИН ${c.iin}` : c.fullName);

/** Таблица денег сделки — одна и та же в оферте, акте и выписке; подписи строк — термины ТЗ п. 5. */
export function moneyTable(m: DealMoney): Block {
  return {
    kind: "table",
    columns: [
      { header: "Показатель", width: 0.65 },
      { header: "Сумма", width: 0.35, align: "right" },
    ],
    rows: [
      ["Цена по оферте", money(m.priceTiyn)],
      ["Защита сделки (2%) — оплачивает Покупатель сверх цены", money(m.protectionTiyn)],
      ["Итого к оплате Покупателем", money(m.buyerTotalTiyn)],
      ["Гарантия оплаты и клиента (4%) — удерживается из цены", money(m.guaranteeTiyn)],
      ["К выплате Мастеру", money(m.payoutTiyn)],
    ],
  };
}

const isTestProvider = (d: ContractData) => d.isDemo || d.provider !== "MANUAL";

function subject(d: ContractData): Block[] {
  const blocks: Block[] = [
    { kind: "paragraph", text: `1.1. Мастер обязуется выполнить работы «${d.subject.title}» по заданию Покупателя и сдать их результат, а Покупатель — принять результат и оплатить его в порядке, установленном договором.` },
  ];
  if (d.subject.details.length > 0) blocks.push({ kind: "paragraph", text: `1.2. Параметры заказа: ${d.subject.details.join("; ")}.` });
  if (d.subject.address) blocks.push({ kind: "paragraph", text: `1.3. Адрес выполнения работ: г. ${d.city}, ${d.subject.address}.` });
  return blocks;
}

function payment(d: ContractData): Block[] {
  const blocks: Block[] = [
    { kind: "paragraph", text: `3.1. После подписания договора обеими Сторонами Покупатель одним платежом оплачивает итоговую сумму — ${money(d.money.buyerTotalTiyn)}.` },
    { kind: "paragraph", text: `3.2. Деньги Покупателя резервируются на эскроу-счёте банка. Платформа «${brand.name}» не принимает и не хранит денежные средства Сторон.` },
    { kind: "paragraph", text: "3.3. Зарезервированные деньги недоступны Мастеру до подписания Покупателем акта приёмки. Авансов нет." },
    {
      kind: "paragraph",
      text: `3.4. После подписания акта приёмки банк по распоряжению перечисляет Мастеру сумму к выплате (${money(d.money.payoutTiyn)}) одним платежом, а платформе — защиту сделки и гарантию оплаты (${money(d.money.platformIncomeTiyn)}) за организацию сделки. Других платежей платформе Стороны не вносят.`,
    },
    { kind: "paragraph", text: "3.5. Каждая операция с деньгами (резервирование, заморозка на время спора, выплата, возврат) отражается в выписке по сделке; Стороны получают уведомление о каждом изменении." },
  ];
  if (isTestProvider(d)) blocks.push({ kind: "paragraph", text: "3.6. Тестовая сделка: платежи проводятся в тестовом режиме, реальные деньги не списываются и не перечисляются." });
  return blocks;
}

export function contractSpec(d: ContractData): PdfSpec {
  const footer = `Договор № ${d.number}, версия ${d.version} · ${TEMPLATE_EDITION} · ${LEGAL_REVIEW_NOTICE}`;
  return {
    title: `Оферта (договор сделки) № ${d.number}`,
    issuedAt: d.issuedAt,
    footer,
    blocks: [
      { kind: "title", text: `ОФЕРТА (ДОГОВОР СДЕЛКИ) № ${d.number}` },
      { kind: "subtitle", text: `версия ${d.version} · г. ${d.city} · ${date(d.issuedAt)}` },
      {
        kind: "paragraph",
        text: `${clientParty(d.client)}, далее — «Покупатель» (заказчик), с одной стороны, и ${executorParty(d.executor)}, далее — «Мастер» (исполнитель), с другой стороны, вместе — «Стороны», заключили настоящий договор через платформу «${brand.name}» о нижеследующем. Договор заключён, когда его подписали обе Стороны.`,
      },

      { kind: "heading", text: "1. Предмет договора" },
      ...subject(d),

      { kind: "heading", text: "2. Цена и деньги сделки" },
      { kind: "paragraph", text: `2.1. Цена работ по договору — ${money(d.money.priceTiyn)}. Из неё складываются суммы сделки:` },
      moneyTable(d.money),

      { kind: "heading", text: "3. Порядок оплаты и выплаты" },
      ...payment(d),

      { kind: "heading", text: "4. Сроки, ход работ и сдача" },
      { kind: "paragraph", text: `4.1. Мастер начинает работы после резервирования денег в банке и выполняет их в течение ${d.durationDays} календарных дней с даты начала работ.` },
      { kind: "paragraph", text: "4.2. Ход сделки отражается статусами, которые видят обе Стороны: «Создана» → «Оплачена, деньги под защитой банка» → «В работе» → «Готово к приёмке» → «Принята» → «Выплачено». Перескочить статус нельзя." },
      { kind: "paragraph", text: "4.3. Мастер сдаёт работу на платформе с фотографиями результата. Платформа сохраняет отметку геолокации сдачи и расстояние до адреса заказа; расстояние больше 500 м отмечается предупреждением и не мешает сдаче." },
      { kind: "paragraph", text: "4.4. Покупатель проверяет результат и подписывает акт приёмки; Мастер подписывает акт ЭЦП. Замечания к результату Покупатель заявляет через спор (раздел 7)." },

      { kind: "heading", text: "5. Гарантия" },
      {
        kind: "paragraph",
        text: d.warrantyMonths > 0 ? `5.1. Мастер даёт гарантию на результат работ ${months(d.warrantyMonths)} с даты подписания акта приёмки.` : "5.1. Гарантийный срок Сторонами не установлен.",
      },

      { kind: "heading", text: "6. Отмена" },
      { kind: "paragraph", text: "6.1. До оплаты любая Сторона может отменить сделку без последствий." },
      { kind: "paragraph", text: "6.2. После оплаты и до начала работ Покупатель может отменить сделку: банк возвращает Покупателю всю оплаченную сумму, включая защиту сделки." },
      { kind: "paragraph", text: "6.3. После начала работ сделка прекращается только решением по спору (раздел 7)." },

      { kind: "heading", text: "7. Споры" },
      { kind: "paragraph", text: "7.1. Любая Сторона может открыть спор на платформе с момента оплаты и до подписания акта приёмки. Пока спор открыт, выплата заморожена, а другие действия по сделке приостановлены." },
      {
        kind: "paragraph",
        text: "7.2. Оператор платформы рассматривает позиции и материалы Сторон и принимает одно из решений: продолжить работу; полностью вернуть деньги Покупателю; разделить сумму — Мастеру выплачивается признанная часть цены за вычетом гарантии оплаты (4%), остаток возвращается Покупателю.",
      },
      { kind: "paragraph", text: "7.3. Решение исполняется операциями банка и отражается в выписке. Порядок раздела 7 не лишает Стороны права обратиться в суд в соответствии с законодательством Республики Казахстан." },

      { kind: "heading", text: "8. Подписание и прочие условия" },
      { kind: "paragraph", text: "8.1. Договор и акт приёмки составляются в электронной форме и подписываются собственноручной подписью на экране и электронной цифровой подписью (ЭЦП) НУЦ РК. Подписывается этот PDF-файл; его хэш SHA-256 платформа хранит вместе с подписями." },
      { kind: "paragraph", text: "8.2. Изображения подписей, время подписи и данные сертификатов ЭЦП приводятся в листе подписей подписанной копии; сам подписанный файл не изменяется." },
      { kind: "paragraph", text: "8.3. Контакты Сторон становятся видны друг другу после заключения договора. Переписку по договору Стороны ведут во внутреннем чате платформы." },
      { kind: "paragraph", text: `8.4. Платформа «${brand.name}» не является стороной договора.` },

      { kind: "heading", text: "Подписи Сторон" },
      {
        kind: "signatures",
        parties: [
          { role: "Покупатель", name: d.client.fullName, caption: "Собственноручная подпись и ЭЦП — в листе подписей" },
          { role: "Мастер", name: d.executor.legalName, caption: "Собственноручная подпись и ЭЦП — в листе подписей" },
        ],
      },
    ],
  };
}
