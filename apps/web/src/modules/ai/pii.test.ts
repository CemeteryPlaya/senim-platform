import { describe, expect, it } from "vitest";
import { scrubPii } from "./pii";

describe("scrubPii — персональные данные не уходят провайдеру", () => {
  it.each([
    ["ИИН", "мой ИИН 900101300015, нужна кухня", "мой ИИН [ИИН], нужна кухня"],
    ["БИН с пробелами", "БИН 210140 012345", "БИН [ИИН]"],
    ["телефон +7 со скобками", "звоните +7 (701) 234-56-78 вечером", "звоните [телефон] вечером"],
    ["телефон через 8", "тел 8 777 123 45 67", "тел [телефон]"],
    ["телефон слитно", "77011234567 после шести", "[телефон] после шести"],
    ["e-mail", "пишите на aigerim.s@mail.kz", "пишите на [e-mail]"],
    ["улица и дом", "живу на ул. Абая, д. 12, кв. 5, нужна прихожая", "живу на [адрес], нужна прихожая"],
    ["проспект", "пр. Мангилик Ел 55 — новостройка", "[адрес] — новостройка"],
    ["микрорайон", "мкр Самал-2, дом 7", "[адрес]"],
    ["квартира отдельно", "квартира 45, третий этаж", "[адрес], третий этаж"],
    ["ЖК в кавычках", "в ЖК «Highvill» сдают квартиры", "в [адрес] сдают квартиры"],
    ["меня зовут", "Меня зовут Айгерим Сапарова, хочу шкаф", "Меня зовут [имя], хочу шкаф"],
    ["ФИО с отчеством", "заказчик Данияр Ахметович ждёт звонка", "заказчик [имя] ждёт звонка"],
    ["фамилия с инициалами", "передайте Касымовой М.А. смету", "передайте [имя] смету"],
    ["подпись в конце", "Спасибо! С уважением, Мадина", "Спасибо! С уважением, [имя]"],
  ])("%s", (_name, input, expected) => {
    expect(scrubPii(input)).toBe(expected);
  });

  it("не трогает размеры, материалы и обычные слова с заглавной буквы", () => {
    const text =
      "Кухня 3,2 м на 2,7 м, глубина 60 см, 3200x2700x600 мм. Фасады МДФ эмаль, Blum, столешница Кварц. Астана, срок 2 месяца";
    expect(scrubPii(text)).toBe(text);
  });

  it("находит несколько данных в одном тексте", () => {
    const out = scrubPii("Иван Петрович, +77011234567, ivan@test.kz, ИИН 900101300015");
    expect(out).not.toMatch(/\d{6,}/);
    expect(out).not.toMatch(/@/);
    expect(out).toContain("[телефон]");
    expect(out).toContain("[e-mail]");
    expect(out).toContain("[ИИН]");
    expect(out).toContain("[имя]");
  });
});
