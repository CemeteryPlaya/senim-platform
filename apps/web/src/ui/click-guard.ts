/**
 * Защита подтверждений от двойного нажатия. Первый клик открывает окно, второй (через 100–300 мс)
 * попадает в то же место экрана — уже в окно, часто прямо в «Да» или в затемнение. Такой клик —
 * продолжение серии (event.detail > 1), а не решение человека. Одиночный клик, даже очень быстрый,
 * проходит: защита по времени гасила бы и осознанное нажатие.
 */

/** Второй и следующие клики одной серии (event.detail > 1). Клавиатура даёт detail = 0. */
export function isRepeatClick(detail: number): boolean {
  return detail > 1;
}
